alter table public.organisations
  add column if not exists created_by uuid references auth.users(id) on delete set null;

alter table public.sites
  add column if not exists created_by uuid references auth.users(id) on delete set null;

create table if not exists public.site_invitations (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references public.organisations(id) on delete cascade,
  site_id uuid not null references public.sites(id) on delete cascade,
  email text not null,
  app_role text not null,
  full_name text,
  status text not null default 'pending',
  invited_by uuid not null references auth.users(id) on delete restrict,
  auth_user_id uuid references auth.users(id) on delete set null,
  expires_at timestamptz not null default (now() + interval '24 hours'),
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint site_invitations_status_check check (status in ('pending','accepted','cancelled','failed','expired')),
  constraint site_invitations_role_check check (app_role in (
    'site_admin','maintenance_manager','maintenance_planner','reliability_engineer',
    'engineer','production_manager','operator','contractor_admin','contractor_engineer'
  ))
);

create unique index if not exists site_invitations_pending_email_site_idx
  on public.site_invitations(site_id, lower(email))
  where status = 'pending';

create table if not exists public.site_admin_audit_log (
  id bigint generated by default as identity primary key,
  organisation_id uuid not null references public.organisations(id) on delete cascade,
  site_id uuid not null references public.sites(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  target_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  previous_value jsonb,
  new_value jsonb,
  created_at timestamptz not null default now()
);

alter table public.site_invitations enable row level security;
alter table public.site_admin_audit_log enable row level security;

