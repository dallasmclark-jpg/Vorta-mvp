on public.site_invitations
for select
to authenticated
using (
  exists (
    select 1
    from public.user_site_access access_row
    where access_row.user_id = (select auth.uid())
      and access_row.site_id = site_invitations.site_id
      and access_row.organisation_id = site_invitations.organisation_id
      and access_row.active
      and access_row.app_role in ('site_owner','site_admin','vorta_admin')
  )
);

